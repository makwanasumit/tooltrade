"use client";

import React, { useMemo, useState } from "react";
import { Download, AlertTriangle, CheckCircle2, Wand2, ShieldAlert } from "lucide-react";
import { CodeEditor } from "@/components/tools/workspace/CodeEditor";
import { TextWorkspace } from "@/components/tools/workspace/TextWorkspace";
import { FindingsList, type ReviewItem } from "@/components/tools/workspace/FindingsList";
import { StatusAnnouncer } from "@/components/tools/workspace/StatusAnnouncer";
import { repairLlmJson } from "./jsonRepairEngine";
import { buildFixPrompt, validateAgainstJsonSchema } from "./schemaValidator";
import { triggerBlobDownload } from "@/lib/file-processing/filenames";
import { bucketFindingCount, trackToolEvent } from "@/lib/analytics/tracker";
import { useToolStage } from "@/components/tools/workspace/ToolFlow";

const SAMPLE_LLM_OUTPUT = `Sure! Here is the user profile you requested:
\`\`\`json
{
  // Generated by model
  id: 42,
  'name': 'Priya Nair',
  active: True,
  notes: None,
  tags: ["ops", "ai-prep",],
\`\`\`
`;

const SAMPLE_SCHEMA = `{
  "$schema": "https://json-schema.org/draft/2020-12/schema",
  "type": "object",
  "required": ["id", "name", "email"],
  "properties": {
    "id": { "type": "integer" },
    "name": { "type": "string" },
    "email": { "type": "string" }
  }
}`;

export function LlmJsonRepairTool() {
  const [rawInput, setRawInput] = useState("");
  const [disabledRules, setDisabledRules] = useState<Set<string>>(new Set());
  const [enableSchema, setEnableSchema] = useState(false);
  const [schemaInput, setSchemaInput] = useState(SAMPLE_SCHEMA);
  const [statusMsg, setStatusMsg] = useState("");

  const repairResult = useMemo(() => {
    if (!rawInput.trim()) return null;
    return repairLlmJson(rawInput, disabledRules);
  }, [rawInput, disabledRules]);

  const schemaResult = useMemo(() => {
    if (!enableSchema || !repairResult?.parsesCleanly) return null;
    try {
      const parsed = JSON.parse(repairResult.repairedText);
      return validateAgainstJsonSchema(parsed, schemaInput);
    } catch {
      return null;
    }
  }, [enableSchema, repairResult, schemaInput]);

  const reviewItems: ReviewItem[] = useMemo(() => {
    if (!repairResult) return [];
    const base: ReviewItem[] = repairResult.changes.map((c) => ({
      id: c.id,
      label: c.label,
      ruleOrType: c.rule,
      location: c.location,
      beforeText: c.beforeText,
      afterText: c.afterText,
      accepted: !disabledRules.has(c.rule),
    }));

    // Also surface any rules the user explicitly disabled so they can re-enable them
    for (const rule of disabledRules) {
      if (!base.some((b) => b.ruleOrType === rule)) {
        base.push({
          id: `disabled-${rule}`,
          label: `Disabled rule: ${rule}`,
          ruleOrType: rule,
          location: "rule toggle",
          beforeText: "(rule skipped by user)",
          afterText: "(unchanged)",
          accepted: false,
        });
      }
    }
    return base;
  }, [repairResult, disabledRules]);

  const handleToggleChange = (id: string) => {
    const target = reviewItems.find((item) => item.id === id);
    if (!target) return;
    setDisabledRules((prev) => {
      const next = new Set(prev);
      if (next.has(target.ruleOrType)) {
        next.delete(target.ruleOrType);
      } else {
        next.add(target.ruleOrType);
      }
      return next;
    });
  };

  const handleCopyFixPrompt = async () => {
    const errs = schemaResult?.errors ?? [];
    const prompt = buildFixPrompt(errs, Boolean(repairResult?.truncatedDetected));
    await navigator.clipboard.writeText(prompt);
    setStatusMsg("Copied fix prompt for LLM regeneration.");
    trackToolEvent("copy_result", { tool_id: "llm-json-repair" });
  };

  useToolStage(rawInput.trim() ? (repairResult ? 2 : 1) : 0);

  return (
    <div className="space-y-6">
      <StatusAnnouncer message={statusMsg} />

      <div className="grid grid-cols-1 lg:grid-cols-2 gap-5">
        <TextWorkspace
          value={rawInput}
          onChange={(val) => {
            setRawInput(val);
            if (val.trim()) {
              const out = repairLlmJson(val, disabledRules);
              trackToolEvent("detector_run", {
                tool_id: "llm-json-repair",
                finding_count_bucket: bucketFindingCount(out.changes.length),
              });
            }
          }}
          onClear={() => {
            setDisabledRules(new Set());
            setStatusMsg("Cleared LLM JSON Repair.");
          }}
          onLoadSample={() => {
            setDisabledRules(new Set());
            setRawInput(SAMPLE_LLM_OUTPUT);
            setStatusMsg("Loaded broken LLM JSON sample.");
          }}
          sampleLabel="Load broken LLM output"
          label="Raw model output"
          placeholder="Paste ChatGPT / Claude / Gemini JSON output (even with markdown fences, comments, or missing closing brackets)..."
          rows={14}
          monospace
          acceptedExtensions=".json,.txt,.md"
          codeFilename="model-output.txt"
        />

        <div className="space-y-2.5">
          <div className="flex flex-wrap items-center justify-between gap-2">
            <span className="text-sm font-semibold">Repaired JSON output</span>
            {repairResult && (
              <span
                className="text-xs font-bold px-2.5 py-0.5 rounded-full"
                style={
                  repairResult.parsesCleanly
                    ? {
                      color: "var(--status-verified-fg)",
                      backgroundColor: "var(--status-verified-bg)",
                    }
                    : {
                      color: "var(--status-finding-fg)",
                      backgroundColor: "var(--status-finding-bg)",
                    }
                }
              >
                {repairResult.status === "unchanged"
                  ? "Unchanged (already valid)"
                  : repairResult.status === "repaired"
                    ? "Repaired (syntax fixed)"
                    : "Syntax still invalid"}
              </span>
            )}
          </div>

          <CodeEditor
            readOnly
            copyable
            copyDisabled={!repairResult?.parsesCleanly}
            value={repairResult?.repairedText ?? ""}
            filename="repaired.json"
            ariaLabel="Repaired JSON output"
            placeholder="Repaired, strict RFC 8259 JSON appears here..."
            minLines={14}
            onCopied={() => {
              setStatusMsg("Repaired JSON copied to clipboard.");
              trackToolEvent("copy_result", { tool_id: "llm-json-repair" });
            }}
            footerNote={
              repairResult ? (
                repairResult.parsesCleanly ? (
                  <span className="code-ok">✓ valid JSON</span>
                ) : (
                  <span className="code-bad">✗ still invalid</span>
                )
              ) : null
            }
          />

          <div className="flex flex-wrap gap-2">
            <button
              type="button"
              disabled={!repairResult?.parsesCleanly}
              onClick={() => {
                if (!repairResult) return;
                triggerBlobDownload(
                  new Blob([repairResult.repairedText], { type: "application/json" }),
                  "repaired.json",
                );
                trackToolEvent("download", { tool_id: "llm-json-repair", output_format: "json" });
              }}
              className="tool-btn tool-btn--ghost tool-btn--sm"
            >
              <Download className="w-3.5 h-3.5" aria-hidden="true" />
              <span>Download .json</span>
            </button>
          </div>
        </div>
      </div>

      {/* Prominent Truncation Warning */}
      {repairResult?.truncatedDetected && (
        <div
          role="alert"
          className="rounded-2xl px-4 py-3.5 text-sm border flex items-start gap-2.5"
          style={{
            color: "var(--status-estimated-fg)",
            backgroundColor: "var(--status-estimated-bg)",
            borderColor: "var(--status-estimated-border)",
          }}
        >
          <AlertTriangle className="w-5 h-5 shrink-0 mt-0.5" aria-hidden="true" />
          <div>
            <p className="font-bold">Data after the cut is missing. Repair only closes brackets.</p>
            <p className="text-xs mt-0.5">
              This output ended mid-structure (Heuristic detection). Verify all fields or ask the
              model to regenerate the incomplete payload.
            </p>
          </div>
        </div>
      )}

      {/* What Changed Diff Panel */}
      {repairResult && (
        <FindingsList
          title="What Changed (Deterministic Repair Log)"
          subtitle="Undo or re-apply any repair rule before copying. Syntax repair never invents missing field values."
          items={reviewItems}
          onToggleItem={handleToggleChange}
          emptyMessage="No syntax repairs were needed — input parsed cleanly as strict JSON."
        />
      )}

      {/* Optional JSON Schema Draft 2020-12 Check */}
      <div className="rounded-2xl border border-[var(--theme-border)] bg-[var(--theme-surface)] p-5 space-y-4">
        <div className="flex flex-wrap items-center justify-between gap-2">
          <label className="inline-flex items-center gap-2.5 text-sm font-bold cursor-pointer">
            <input
              type="checkbox"
              checked={enableSchema}
              onChange={(e) => setEnableSchema(e.target.checked)}
              className="w-4 h-4 accent-[var(--swatch-sky)]"
            />
            <span>Validate against JSON Schema (Draft 2020-12)</span>
          </label>
          <span className="text-xs text-[var(--theme-text-muted)]">
            Separates Syntax Repaired from Schema Violation
          </span>
        </div>

        {enableSchema && (
          <div className="space-y-4">
            <CodeEditor
              value={schemaInput}
              onChange={setSchemaInput}
              filename="schema.json"
              ariaLabel="JSON Schema definition"
              minLines={7}
              maxHeight="22rem"
            />

            {schemaResult?.schemaParseError && (
              <p className="text-xs text-[var(--status-finding-fg)] font-semibold">
                Schema JSON error: {schemaResult.schemaParseError}
              </p>
            )}

            {schemaResult && schemaResult.unsupportedKeywords.length > 0 && (
              <div
                className="rounded-xl px-3.5 py-2.5 text-xs border"
                style={{
                  color: "var(--status-estimated-fg)",
                  backgroundColor: "var(--status-estimated-bg)",
                  borderColor: "var(--status-estimated-border)",
                }}
              >
                Unsupported schema keywords listed (not silently ignored):{" "}
                <span className="font-mono font-semibold">
                  {schemaResult.unsupportedKeywords.join(", ")}
                </span>
              </div>
            )}

            {schemaResult && !schemaResult.schemaParseError && (
              <div className="space-y-3">
                {schemaResult.valid ? (
                  <div
                    className="rounded-xl px-4 py-3 text-sm border flex items-center gap-2 font-semibold"
                    style={{
                      color: "var(--status-verified-fg)",
                      backgroundColor: "var(--status-verified-bg)",
                      borderColor: "var(--status-verified-border)",
                    }}
                  >
                    <CheckCircle2 className="w-4 h-4" aria-hidden="true" />
                    <span>Schema check passed!</span>
                  </div>
                ) : (
                  <div
                    className="rounded-xl px-4 py-3.5 text-sm border space-y-2.5"
                    style={{
                      color: "var(--status-finding-fg)",
                      backgroundColor: "var(--status-finding-bg)",
                      borderColor: "var(--status-finding-border)",
                    }}
                  >
                    <div className="flex flex-wrap items-center justify-between gap-2">
                      <span className="font-bold inline-flex items-center gap-1.5">
                        <ShieldAlert className="w-4 h-4" aria-hidden="true" />
                        Schema Violation — Needs Regeneration ({schemaResult.errors.length})
                      </span>
                      <button
                        type="button"
                        onClick={() => void handleCopyFixPrompt()}
                        className="tool-btn tool-btn--ink tool-btn--sm"
                      >
                        <Wand2 className="w-3.5 h-3.5" aria-hidden="true" />
                        <span>Copy fix prompt</span>
                      </button>
                    </div>
                    <ul className="space-y-1 text-xs font-mono list-disc pl-5">
                      {schemaResult.errors.map((err, i) => (
                        <li key={i}>
                          <strong>{err.instanceLocation}</strong>: {err.error}
                        </li>
                      ))}
                    </ul>
                  </div>
                )}
              </div>
            )}
          </div>
        )}
      </div>
    </div>
  );
}

